"""Request/response schemas for the meeting intelligence API."""
from __future__ import annotations

from pydantic import BaseModel, Field, model_validator


class Utterance(BaseModel):
    """One turn of speech in the meeting."""

    speaker: str = Field(default="Speaker", description="Speaker label or name.")
    text: str = Field(..., min_length=1, description="What the speaker said.")


class MeetingRequest(BaseModel):
    """Input payload.

    Provide either `utterances` (preferred — speaker-labeled turns, e.g. from a
    diarized transcription service) or a raw `transcript` string, which gets
    auto-chunked into sentence-like pieces before scoring.
    """

    meeting_id: str | None = Field(default=None, description="Optional identifier echoed back in the response.")
    utterances: list[Utterance] | None = Field(
        default=None, description="Speaker-labeled turns. Preferred over `transcript` when available."
    )
    transcript: str | None = Field(
        default=None, description="Raw transcript text, used only if `utterances` is not provided."
    )

    @model_validator(mode="after")
    def _require_content(self) -> "MeetingRequest":
        has_utterances = bool(self.utterances)
        has_transcript = bool(self.transcript and self.transcript.strip())
        if not has_utterances and not has_transcript:
            raise ValueError("Provide either a non-empty 'utterances' list or a non-empty 'transcript' string.")
        return self

    model_config = {
        "json_schema_extra": {
            "examples": [
                {
                    "meeting_id": "standup-2026-08-11",
                    "utterances": [
                        {"speaker": "Alice", "text": "I think we should use PostgreSQL instead of MongoDB."},
                        {"speaker": "Bob", "text": "Agreed, let's go with Postgres for the relational data."},
                        {"speaker": "Alice", "text": "Great, it's decided then, we'll use PostgreSQL."},
                        {"speaker": "Carol", "text": "I'll set up the database schema by Friday."},
                    ],
                }
            ]
        }
    }


class EvidenceChunk(BaseModel):
    """One transcript chunk that was selected as evidence for the narrative summary."""

    speaker: str
    text: str
    importance: float
    decision_score: float
    is_decision: bool
    is_action: bool


class DecisionBullet(BaseModel):
    """One fused, human-readable decision bullet."""

    bullet: str
    confidence: float = Field(description="Max decision-classifier confidence across the fused evidence group.")
    speakers: str
    evidence: list[str] = Field(description="Raw flagged sentences that were fused into this bullet.")


class ActionBullet(BaseModel):
    """One fused, human-readable action item."""

    action: str
    assignee: str | None = Field(description="Extracted by the BIO tagger, not generated — avoids hallucination.")
    deadline: str | None = Field(description="Extracted by the BIO tagger, not generated — avoids hallucination.")
    speakers: str
    evidence: list[str] = Field(description="Raw flagged sentences that were fused into this bullet.")


class MeetingIntelligenceResponse(BaseModel):
    meeting_id: str
    summary: str = Field(description="Narrative paragraph summary generated by the fine-tuned BART model.")
    key_decisions: list[DecisionBullet]
    action_items: list[ActionBullet]
    selected_evidence: list[EvidenceChunk] = Field(
        description="The transcript chunks actually supplied to the summarizer, for explainability."
    )
    bullet_fusion_used: bool = Field(
        description="False if the T5 fusion model wasn't found; bullets then fall back to raw joined sentences."
    )
